export function pickQuizQuestion(mode: CurriculumMode, tileType: 'quiz_basic' | 'quiz_visual'): QuizQuestion {
  let pool: QuizQuestion[];
  if (mode === 'mode1') {
    pool = QUIZ_QUESTIONS.filter((q) => q.mode === 'mode1');
  } else if (mode === 'mode2') {
    pool = QUIZ_QUESTIONS.filter((q) => q.mode === 'mode2');
  } else {
    // Mode 3: Tile 3 prefers Mode 1 basics, Tile 11 prefers Mode 2 visual/charts
    const targetMode = tileType === 'quiz_basic' ? 'mode1' : 'mode2';
    pool = QUIZ_QUESTIONS.filter((q) => q.mode === targetMode);
  }
  const idx = Math.floor(Math.random() * pool.length);
  return pool[idx];
}

export function pickUpgradeChallenge(): UpgradeChallenge {
  const idx = Math.floor(Math.random() * UPGRADE_CHALLENGES.length);
  return UPGRADE_CHALLENGES[idx];
}

export function pickBuyDiscountPuzzle(): BuyDiscountPuzzle {
  const idx = Math.floor(Math.random() * BUY_DISCOUNT_PUZZLES.length);
  return BUY_DISCOUNT_PUZZLES[idx];
}
